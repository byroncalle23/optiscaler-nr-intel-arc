"""Embed the native HLSL sources, recursively expanding local includes."""
import argparse
import hashlib
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
native = root / 'src/native'
target = native / 'embedded_shaders.h'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()

def expand(name, stack=()):
    if name in stack or not re.fullmatch(r'[a-z_]+\.hlsl', name):
        raise ValueError(f'Invalid shader include: {name}')
    text = (native / name).read_text(encoding='utf-8')
    return re.sub(r'^\s*#include "([a-z_]+\.hlsl)"\s*$',
                  lambda match: expand(match[1], (*stack, name)), text, flags=re.MULTILINE)

parts = ['// Generated by tools/embed_native_shaders.py; edit the original HLSL.\n',
         '#pragma once\n#include <string_view>\n',
         'struct EmbeddedNativeShader {std::string_view name,source,sha256;};\n',
         'inline constexpr EmbeddedNativeShader embeddedNativeShaders[]={\n']
for path in sorted(native.glob('*_ops.hlsl')):
    source = expand(path.name)
    if ')NR_HLSL"' in source:
        raise ValueError('Raw-string delimiter collision')
    digest = hashlib.sha256(source.encode('utf-8')).hexdigest()
    parts.append(f'{{"{path.name}",R"NR_HLSL({source})NR_HLSL","{digest}"}},\n')
parts.append('};\n')
result = ''.join(parts)
if args.check:
    if not target.exists() or target.read_text(encoding='utf-8') != result:
        raise SystemExit('Embedded shaders are stale; run tools/embed_native_shaders.py')
    print('Embedded shader sources match the HLSL originals.')
else:
    target.write_text(result, encoding='utf-8', newline='\n')
    print(f'Embedded {len(list(native.glob("*_ops.hlsl")))} shaders.')
